/**
 * Conservative C emitter — the TypeScript port of analyzer/src/emit_c.rs.
 *
 * Phase 0/1 philosophy: emit every value BOXED (`tsv`) and lower each
 * instruction to the runtime's dynamic helpers. Behaviorally equivalent to the
 * Rust analyzer's output (same stdout) but skips the type-specialized fast paths
 * (int/string specialization, devirt, SROA) — those are Phase 2 perf work.
 * Correctness first; the differential harness (vs the Rust analyzer + node)
 * proves equivalence.
 *
 * GC discipline (conservative): every local is a rooted `tsv` slot — we
 * `ts_gc_root` all of them at function entry and `ts_gc_unroot` before each
 * return. Rooting a primitive slot is harmless (GC ignores non-heap values), so
 * this needs no escape analysis. Precise rooting is a Phase 2 perf concern.
 *
 * The program-INDEPENDENT runtime preamble (proto setups, built-in class
 * registration, Math/JSON/console globals) is lifted verbatim from a proven Rust
 * emit (templates/runtime_preamble.c) for Phase 0/1. Generator port is Phase 1.
 */
import { Program, FunctionDef, Inst } from "./ir";
import { RUNTIME_PREAMBLE } from "./preamble_gen";

/** Thrown when we hit an instruction/op we have not ported yet. The harness
 *  catches these and tallies them as the Phase 1 work-list. */
export class UnportedError extends Error {}

/** Per-program lowering context (function symbols, this-taking, well-known
 *  symbol keys). Set once at the top of emitProgram. */
interface Ctx {
  fnSymById: Map<number, string>;
  takesThis: Set<number>;
  wksym: Map<number, number>; // name_id -> wksym_id
  protoRuntime: Map<string, string>; // "array.map" -> "ts_arrproto_map"
  fnvalAdapters: Set<string>; // ts_fnval_* adapters defined in the preamble
}
let CTX: Ctx = { fnSymById: new Map(), takesThis: new Set(), wksym: new Map(), protoRuntime: new Map(), fnvalAdapters: new Set() };

/** A method/symbol property key (matches emit_c's method_key_str). */
function methodKey(nameId: number): string {
  const w = CTX.wksym.get(nameId);
  return w !== undefined ? `TS_KEY_WKSYM(${w}u)` : `TS_KEY_METHOD(${nameId}u)`;
}

function fnSym(fn: FunctionDef): string {
  const name = (fn.name ?? "").replace(/[^A-Za-z0-9_]/g, "_");
  return `fn_${fn.id}_${name}`;
}

function visibleName(fn: FunctionDef): string {
  const n = fn.name ?? "";
  return n.startsWith("__") ? "" : n;
}

function cStringLit(s: string): string {
  return '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
}

/** C string literal from raw bytes: printable ASCII as-is, the rest as 3-digit
 *  octal escapes (always 3 digits so a following digit is never absorbed).
 *  Mirrors emit_c's c_bytes_lit. */
function cBytesLit(bytes: number[]): string {
  let esc = "";
  for (const b of bytes) {
    if (b === 0x5c) esc += "\\\\";
    else if (b === 0x22) esc += '\\"';
    else if (b === 0x0a) esc += "\\n";
    else if (b === 0x0d) esc += "\\r";
    else if (b === 0x09) esc += "\\t";
    else if (b >= 0x20 && b <= 0x7e) esc += String.fromCharCode(b);
    else esc += "\\" + b.toString(8).padStart(3, "0");
  }
  return '"' + esc + '"';
}

function header(needsRegexp: boolean): string {
  return (
    "/* generated by emit_c.ts (conservative boxed; self-hosting port) */\n" +
    '#include "ts_rt.h"\n' +
    // Always pull in the Unicode adapter: the string prototype registers the
    // ts_unicode_strproto_* case-mappers, so the symbols must be declared and the
    // marker must trigger the optional unicode runtime object to link. (Phase 2:
    // gate this on actual use.)
    '#include "unicode/ts_unicode_adapter.h"\n' +
    // Marker the link harness greps for to pull in the optional unicode object.
    "#define TSAOT_NEEDS_UNICODE 1\n" +
    // RegExp (gated on actual use): the marker pulls in the optional regexp
    // runtime object, and the adapter header declares ts_regexp_adapter_*_tsv.
    (needsRegexp ? '#define TSAOT_NEEDS_REGEXP 1\n#include "regexp/ts_regexp_adapter.h"\n' : "") +
    "\n" +
    "#if defined(__GNUC__) || defined(__clang__)\n" +
    "#define TS_AOT_INLINE static inline __attribute__((always_inline))\n" +
    "#else\n" +
    "#define TS_AOT_INLINE static inline\n" +
    "#endif\n\n\n"
  );
}

function tables(prog: Program): string {
  const fns = prog.functions;
  let s = "";
  for (const fn of fns) s += `static tsv ${fnSym(fn)}(tsv* args, int nargs);\n`;
  s += "\ntypedef tsv (*ts_fn)(tsv*, int);\n";
  const n = fns.length;
  s += `static ts_fn FN_TABLE[${n}] = {${fns.map(fnSym).join(", ")}${n ? ", " : ""}};\n`;
  s += `static const uint32_t FN_ARITY[${n}] = {${fns.map((f) => `${f.arity ?? 0}`).join(", ")}${n ? ", " : ""}};\n`;
  s += `static const char* FN_NAME[${n}] = {${fns.map((f) => cStringLit(visibleName(f))).join(", ")}${n ? ", " : ""}};\n\n`;
  s += `static const uint8_t FN_HAS_PROTOTYPE[${n}] = {${fns.map((f) => (f.hasPrototype ? "1" : "0")).join(", ")}${n ? ", " : ""}};\n\n`;
  const classes = (prog.classes ?? []) as { name?: string }[];
  if (classes.length === 0) {
    s += `static const char* CLASS_NAME[1] = {"", };\n`;
  } else {
    s += `static const char* CLASS_NAME[${classes.length}] = {${classes
      .map((c) => cStringLit(c.name ?? ""))
      .join(", ")}, };\n`;
  }
  return s;
}

