/** Generate the built-in prototype setup functions from the IR's per-program
 *  protoMethods tables. CRUCIAL: methodIds are assigned per program, so these
 *  MUST use the program's ids (not a fixed template) — otherwise a Method-callee
 *  proto lookup `ts_get(recv, TS_KEY_METHOD(id))` can hit the wrong builtin. */
function generateProtoSetups(prog: Program, needsRegexp: boolean): string {
  const unicodeCase = new Set(["toUpperCase", "toLowerCase", "toLocaleUpperCase", "toLocaleLowerCase"]);
  const specs: { fn: string; reg: string; field: string; init: string[]; special?: boolean; unicode?: boolean }[] = [
    { fn: "ts_setup_object_proto", reg: "ts_object_proto_register", field: "objectProtoMethods",
      init: ["OBJECT_PROTO = ts_new_proto(); ts_gc_root(&OBJECT_PROTO);", "ts_install_object_proto(OBJECT_PROTO);", "ts_function_proto_init();"], special: true },
    { fn: "ts_setup_array_proto", reg: "ts_array_proto_register", field: "arrayProtoMethods", init: ["ts_array_proto_init();"] },
    { fn: "ts_setup_promise_proto", reg: "ts_promise_proto_register", field: "promiseProtoMethods", init: ["ts_promise_proto_init();"] },
    { fn: "ts_setup_map_proto", reg: "ts_map_proto_register", field: "mapProtoMethods", init: ["ts_map_proto_init();"] },
    { fn: "ts_setup_set_proto", reg: "ts_set_proto_register", field: "setProtoMethods", init: ["ts_set_proto_init();"] },
    { fn: "ts_setup_weakmap_proto", reg: "ts_weakmap_proto_register", field: "weakMapProtoMethods", init: ["ts_weakmap_proto_init();"] },
    { fn: "ts_setup_weakset_proto", reg: "ts_weakset_proto_register", field: "weakSetProtoMethods", init: ["ts_weakset_proto_init();"] },
    { fn: "ts_setup_headers_proto", reg: "ts_headers_proto_register", field: "headersProtoMethods", init: ["ts_headers_proto_init();"] },
    { fn: "ts_setup_function_proto", reg: "ts_function_proto_register", field: "functionProtoMethods", init: ["ts_function_proto_init();"] },
    { fn: "ts_setup_string_proto", reg: "ts_string_proto_register", field: "stringProtoMethods", init: ["ts_string_proto_init();"], unicode: true },
    { fn: "ts_setup_number_proto", reg: "ts_number_proto_register", field: "numberProtoMethods", init: ["ts_number_proto_init();"] },
    { fn: "ts_setup_boolean_proto", reg: "ts_boolean_proto_register", field: "booleanProtoMethods", init: ["ts_boolean_proto_init();"] },
  ];
  let s = "static tsv OBJECT_PROTO;\n";
  for (const sp of specs) {
    s += `static void ${sp.fn}(void){\n`;
    for (const l of sp.init) s += `  ${l}\n`;
    const arr = (prog[sp.field] ?? []) as { name: string; runtime: string; methodId: number }[];
    for (const m of arr) {
      const runtime = sp.unicode && unicodeCase.has(m.name) ? `ts_unicode_strproto_${m.name}` : m.runtime;
      s += `  ${sp.reg}(TS_KEY_METHOD(${m.methodId}u), ${JSON.stringify(m.name)}, ${runtime});\n`;
      if (sp.special) {
        if (m.name === "toString") s += `  ts_set_tostring_key(TS_KEY_METHOD(${m.methodId}u));\n`;
        else if (m.name === "valueOf") s += `  ts_set_valueof_key(TS_KEY_METHOD(${m.methodId}u));\n`;
        else if (m.name === "toJSON") s += `  ts_set_tojson_key(TS_KEY_METHOD(${m.methodId}u));\n`;
      }
    }
    s += "}\n";
  }
  // RegExp.prototype.test/exec: emit_c generates these fixed adapter bodies and
  // registers them under the program's methodIds.
  if (needsRegexp) {
    s += "static tsv ts_regexpproto_test(tsv* args, int nargs){\n" +
      '  if(nargs < 1 || !ts_regexp_is_object(args[0])) { ts_throw_type_error_msg("RegExp.prototype.test called on incompatible receiver"); return TS_UNDEFINED; }\n' +
      "  tsv input = nargs > 1 ? args[1] : TS_UNDEFINED;\n  tsv s = ts_to_string_v(input);\n  return ts_regexp_adapter_object_test_tsv(args[0], s);\n}\n";
    s += "static tsv ts_regexpproto_exec(tsv* args, int nargs){\n" +
      '  if(nargs < 1 || !ts_regexp_is_object(args[0])) { ts_throw_type_error_msg("RegExp.prototype.exec called on incompatible receiver"); return TS_UNDEFINED; }\n' +
      "  tsv input = nargs > 1 ? args[1] : TS_UNDEFINED;\n  tsv s = ts_to_string_v(input);\n  return ts_regexp_adapter_object_exec_tsv(args[0], s);\n}\n";
    s += "static void ts_setup_regexp_proto(void){\n  ts_regexp_proto_init();\n";
    const arr = (prog.regexpProtoMethods ?? []) as { name: string; runtime: string; methodId: number }[];
    for (const m of arr) s += `  ts_regexp_proto_register(TS_KEY_METHOD(${m.methodId}u), ${JSON.stringify(m.name)}, ${m.runtime});\n`;
    s += "}\n";
  }
  return s;
}

// ---- static Str16 literals ----

/** Str16 literal units (joined key) -> literal id. Filled per program. */
let STR16: Map<string, number> = new Map();

/** Collect every Str16 const and emit one static non-heap string struct per
 *  literal. Storage matches the runtime: UTF-16LE bytes + 2-byte NUL when any
 *  unit > 0xff, else Latin-1 bytes + NUL; len counts UNITS; hash is the
 *  runtime's per-unit FNV (lo byte then hi byte). */
function str16Decls(prog: Program): string {
  STR16 = new Map();
  const lits: number[][] = [];
  walkProgram(prog, (i) => {
    if (i.kind === "Const" && i.value && i.value.kind === "Str16") {
      const units = i.value.units as number[];
      const key = units.join(",");
      if (!STR16.has(key)) {
        STR16.set(key, lits.length);
        lits.push(units);
      }
    }
  });
  if (lits.length === 0) return "";
  let s = "/* static Str16 literals (UTF-16 payloads, non-heap) */\n";
  lits.forEach((units, id) => {
    const utf16 = units.some((u) => u > 0xff);
    const bytes: number[] = [];
    if (utf16) {
      for (const u of units) bytes.push(u & 0xff, (u >> 8) & 0xff);
      bytes.push(0, 0);
    } else {
      for (const u of units) bytes.push(u & 0xff);
      bytes.push(0);
    }
    let h = 2166136261;
    for (const u of units) {
      h = Math.imul(h ^ (u & 0xff), 16777619);
      h = Math.imul(h ^ ((u >> 8) & 0xff), 16777619);
    }
    h = h >>> 0;
    const flags = ["TS_STR_FLAG_HASHED"];
    if (units.every((u) => u < 0x80)) flags.push("TS_STR_FLAG_ASCII");
    if (utf16) flags.push("TS_STR_FLAG_UTF16");
    flags.push("TS_STR_FLAG_STATIC");
    s +=
      `static struct { ts_gc_header h; uint32_t len, hash, flags; tsv parent; uint32_t offset; char data[${bytes.length}]; } ` +
      `TS_STRLIT16_${id} = { { TS_KIND_STRING, 0, TS_GEN_NONHEAP, 0, 0 }, ${units.length}u, ${h}u, ${flags.join(" | ")}, TS_UNDEFINED, 0u, {${bytes.join(", ")}} };\n`;
  });
  return s + "\n";
}

// ---- instruction lowering ----

function numLit(v: number): string {
  if (Number.isNaN(v)) return "(0.0/0.0)";
  if (v === Infinity) return "(1.0/0.0)";
  if (v === -Infinity) return "(-1.0/0.0)";
  if (Object.is(v, -0)) return "(-0.0)";
  if (Number.isInteger(v)) return `${v}.0`;
  return `${v}`;
}

function emitConst(value: any): string {
  switch (value.kind) {
    case "Num":
      return `ts_num(${numLit(value.value)})`;
    case "NaN":
      return "ts_num((0.0/0.0))";
    case "PosInf":
      return "ts_num((1.0/0.0))";
    case "NegInf":
      return "ts_num((-1.0/0.0))";
    case "NegZero":
      return "ts_num((-0.0))";
    case "Bool":
      return `ts_bool(${value.value ? 1 : 0})`;
    case "Undef":
      return "TS_UNDEFINED";
    case "Null":
      return "TS_NULL";
    case "Str": {
      // Conservative: build the string at runtime from a byte-array compound
      // literal (no C escaping pitfalls; ts_new_string copies the bytes).
      // Phase 2: static TS_STRLIT_ tables.
      const bytes = utf8Bytes(value.value);
      const arr = bytes.length ? `(const char[]){${bytes.join(", ")}}` : `""`;
      return `ts_new_string(${arr}, ${bytes.length}u)`;
    }
    case "Str16": {
      // Raw UTF-16 code units (lone surrogates etc. — not UTF-8 representable):
      // a static non-heap string literal in the runtime's UTF-16 storage form,
      // collected by a prepass (str16Decls). Mirrors emit_c's TS_STRLIT_ emission.
      const id = STR16.get((value.units as number[]).join(","));
      if (id === undefined) throw new UnportedError("ConstVal Str16 not collected");
      return `ts_str_v(&TS_STRLIT16_${id})`;
    }
    default:
      throw new UnportedError(`ConstVal kind '${value.kind}'`);
  }
}

const RELOP: Record<string, number> = { "<": 0, "<=": 1, ">": 2, ">=": 3 };

function emitBinOp(i: any): string {
  const a = `L${i.lhs}`, b = `L${i.rhs}`;
  switch (i.op) {
    case "+": return `ts_add(${a}, ${b})`;
    case "-": return `ts_num(ts_number_coerce(${a}) - ts_number_coerce(${b}))`;
    case "*": return `ts_num(ts_number_coerce(${a}) * ts_number_coerce(${b}))`;
    case "/": return `ts_num(ts_number_coerce(${a}) / ts_number_coerce(${b}))`;
    case "%": return `ts_num(fmod(ts_number_coerce(${a}), ts_number_coerce(${b})))`;
    case "**": return `ts_num(pow(ts_number_coerce(${a}), ts_number_coerce(${b})))`;
    case "<": case "<=": case ">": case ">=":
      return `ts_bool(ts_relational(${a}, ${b}, ${RELOP[i.op]}))`;
    case "===": return `ts_bool(ts_strict_eq(${a}, ${b}))`;
    case "!==": return `ts_bool(!ts_strict_eq(${a}, ${b}))`;
    case "==": return `ts_bool(ts_loose_eq(${a}, ${b}))`;
    case "!=": return `ts_bool(!ts_loose_eq(${a}, ${b}))`;
    case "&": return `ts_num((double)(ts_to_int32(ts_number_coerce(${a})) & ts_to_int32(ts_number_coerce(${b}))))`;
    case "|": return `ts_num((double)(ts_to_int32(ts_number_coerce(${a})) | ts_to_int32(ts_number_coerce(${b}))))`;
    case "^": return `ts_num((double)(ts_to_int32(ts_number_coerce(${a})) ^ ts_to_int32(ts_number_coerce(${b}))))`;
    case "<<": return `ts_num((double)(ts_to_int32(ts_number_coerce(${a})) << (ts_to_uint32(ts_number_coerce(${b})) & 31)))`;
    case ">>": return `ts_num((double)(ts_to_int32(ts_number_coerce(${a})) >> (ts_to_uint32(ts_number_coerce(${b})) & 31)))`;
    case ">>>": return `ts_num((double)((uint32_t)ts_to_int32(ts_number_coerce(${a})) >> (ts_to_uint32(ts_number_coerce(${b})) & 31)))`;
    default:
      throw new UnportedError(`BinOp op '${i.op}'`);
  }
}

function emitUnOp(i: any): string {
  const x = `L${i.operand}`;
  switch (i.op) {
    case "typeof": return `ts_typeof(${x})`;
    case "!": return `ts_bool(!ts_truthy_fast(${x}))`;
    case "-": return `ts_num(-ts_number_coerce(${x}))`;
    case "~": return `ts_num((double)(~ts_to_int32(ts_number_coerce(${x}))))`;
    case "nullish": return `ts_bool(ts_is_nullish_fast(${x}))`;
    case "isundef": return `ts_bool(ts_is_undefined_fast(${x}))`;
    default:
      throw new UnportedError(`UnOp op '${i.op}'`);
  }
}

