/* rx_unicode.c: case mapping and the Unicode property tables of the regexp engine
   (docs/regexp_vm_design.md; the tables are generated by scripts/gen_rx_unicode.py). */
#include "rx_internal.h"
#include "rx_unicode_tables.h"

/* The non-`u` Canonicalize over code units and the `u` simple case folding over code points,
   as flat BMP tables built on first use from the generated lists (a mapped unit stores the
   mapping, an identity unit 0; the supplementary folds are searched in the list). */
static uint16_t* g_canon_bmp;   /* 65536 entries: mapping + 1, 0 = identity */
static uint16_t* g_fold_bmp;
const uint16_t* rx_g_canon_bmp;
const uint16_t* rx_g_fold_bmp;
void rx_unicode_init(void){
  if (rx_g_canon_bmp) return;
  rx_canon_nonu(0); rx_fold_u(0);
  rx_g_canon_bmp = g_canon_bmp; rx_g_fold_bmp = g_fold_bmp;
}
static void build_bmp(uint16_t** tab, const uint32_t* list, uint32_t n){
  uint16_t* t = (uint16_t*)calloc(65536, sizeof(uint16_t));
  if (!t) abort();
  for (uint32_t i = 0; i < n; i++){
    uint32_t cp = list[2*i], m = list[2*i+1];
    if (cp < 0x10000 && m < 0x10000) t[cp] = (uint16_t)(m + 1u);
  }
  *tab = t;
}
uint32_t rx_canon_nonu(uint32_t cu){
  if (cu >= 0x10000) return cu;
  if (!g_canon_bmp) build_bmp(&g_canon_bmp, rx_canon_list, RX_CANON_LIST_N);
  uint16_t m = g_canon_bmp[cu];
  return m ? (uint32_t)(m - 1u) : cu;
}
uint32_t rx_fold_u(uint32_t cp){
  if (cp < 0x10000){
    if (!g_fold_bmp) build_bmp(&g_fold_bmp, rx_fold_list, RX_FOLD_LIST_N);
    uint16_t m = g_fold_bmp[cp];
    return m ? (uint32_t)(m - 1u) : cp;
  }
  uint32_t lo = 0, hi = RX_FOLD_LIST_N;
  while (lo < hi){
    uint32_t mid = (lo + hi) / 2;
    uint32_t c = rx_fold_list[2*mid];
    if (cp < c) hi = mid; else if (cp > c) lo = mid + 1; else return rx_fold_list[2*mid+1];
  }
  return cp;
}
const uint32_t* rx_canon_pairs(uint32_t* n){ *n = RX_CANON_LIST_N; return rx_canon_list; }
const uint32_t* rx_fold_pairs(uint32_t* n){ *n = RX_FOLD_LIST_N; return rx_fold_list; }

/* \p{...}: name (and kind: 0 binary or a lone General_Category value, 1 gc=, 2 sc=, 3 scx=)
   to a range table; NULL when unknown. Names are matched exactly (no loose matching). */
const uint32_t* rx_prop_lookup(const char* name, uint32_t name_len, int kind, uint32_t* nranges){
  uint32_t lo = 0, hi = RX_PROP_NAMES_N;
  while (lo < hi){
    uint32_t mid = (lo + hi) / 2;
    const rx_prop_name* e = &rx_prop_names[mid];
    size_t el = strlen(e->name);
    size_t cl = el < name_len ? el : name_len;
    int c = memcmp(e->name, name, cl);
    if (c == 0) c = (el > name_len) - (el < name_len);
    if (c == 0){
      /* entries with the same name are adjacent, ordered by kind */
      uint32_t i = mid;
      while (i > 0 && strcmp(rx_prop_names[i-1].name, e->name) == 0) i--;
      for (; i < RX_PROP_NAMES_N && strcmp(rx_prop_names[i].name, e->name) == 0; i++){
        int k = rx_prop_names[i].kind;
        if (k == kind || (kind == 0 && k == 1)){ *nranges = rx_prop_names[i].n; return rx_prop_names[i].ranges; }
      }
      return NULL;
    }
    if (c < 0) lo = mid + 1; else hi = mid;
  }
  return NULL;
}
int rx_is_id_start(uint32_t cp){ return rx_ranges_has(rx_id_start_ranges, rx_id_start_n, cp); }
int rx_is_id_continue(uint32_t cp){ return rx_ranges_has(rx_id_continue_ranges, rx_id_continue_n, cp); }

/* A class table from a set: a bitmap for the members below 256 and the ranges above. */
void rx_class_bitmap_ranges(rx_set* out, const rx_cpset* s){
  memset(out->bits, 0, sizeof out->bits);
  uint32_t first_wide = s->n;
  for (uint32_t i = 0; i < s->n; i++){
    uint32_t lo = s->r[2*i], hi = s->r[2*i+1];
    for (uint32_t c = lo; c < 256u && c <= hi; c++) out->bits[c >> 3] |= (uint8_t)(1u << (c & 7u));
    if (hi >= 256u && first_wide == s->n) first_wide = i;
  }
  out->ranges = s->n > first_wide ? s->r + 2*first_wide : NULL;
  out->nranges = s->n - first_wide;
}
