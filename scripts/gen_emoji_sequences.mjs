#!/usr/bin/env node
// The properties of strings of the `v` flag (\p{RGI_Emoji} and its parts): runtime/regexp/rx_emoji_sequences.h, from the
// lists in test262's generated property tests, which come from the Unicode data files.
//   node scripts/gen_emoji_sequences.mjs <test262 checkout>
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
const src = process.argv[2];
const dir = path.join(src, "test/built-ins/RegExp/property-escapes/generated/strings");
const names = ["Basic_Emoji", "Emoji_Keycap_Sequence", "RGI_Emoji_Modifier_Sequence", "RGI_Emoji_Flag_Sequence", "RGI_Emoji_Tag_Sequence", "RGI_Emoji_ZWJ_Sequence"];
const cLiteral = (s) => {
  const bytes = Buffer.from(s, "utf8");
  let out = "", col = 0;
  for (const b of bytes) {
    const e = b >= 32 && b < 127 && b !== 34 && b !== 92 && b !== 63 ? String.fromCharCode(b) : "\\" + b.toString(8).padStart(3, "0");
    out += e;
    col += e.length;
    if (col > 110) { out += '"\n  "'; col = 0; }
  }
  return `"${out}"`;
};
let unicode = "";
let text = "/* Generated by scripts/gen_emoji_sequences.mjs from test262's property tests: the members of the\n   properties of strings, separated by newlines. RGI_Emoji is their union. */\n";
text += "typedef struct { const char* name; const char* strings; } rx_string_property;\n";
text += "static const rx_string_property rx_string_properties[] = {\n";
for (const name of names) {
  const file = fs.readFileSync(path.join(dir, `${name}.js`), "utf8");
  unicode = file.match(/Unicode v([\d.]+)/)?.[1] ?? unicode;
  let strings;
  vm.runInNewContext(file, { testPropertyOfStrings: (o) => { strings = o.matchStrings; } });
  text += `  { "${name}",\n  ${cLiteral(strings.join("\n"))} },\n`;
}
text += "};\n";
fs.writeFileSync(new URL("../runtime/regexp/rx_emoji_sequences.h", import.meta.url), `/* Unicode ${unicode} */\n` + text);
