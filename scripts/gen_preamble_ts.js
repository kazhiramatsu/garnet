#!/usr/bin/env node
// Regenerate analyzer_ts/src/preamble_gen.ts from templates/runtime_preamble.c.
// The preamble is embedded as a string constant so the emitter has NO filesystem
// dependency (a self-hosting requirement: the garnet-compiled native analyzer
// has no fs/path/__dirname).
//
// Run after editing templates/runtime_preamble.c:
//   node scripts/gen_preamble_ts.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "analyzer_ts", "templates", "runtime_preamble.c"), "utf8");
const out =
  "// GENERATED by scripts/gen_preamble_ts.js from templates/runtime_preamble.c.\n" +
  "// Do not edit by hand; regenerate after template changes.\n" +
  "export const RUNTIME_PREAMBLE: string =\n" +
  src
    .split("\n")
    .map((line, i, arr) => JSON.stringify(i < arr.length - 1 ? line + "\n" : line))
    .join(" +\n") +
  ";\n";
fs.writeFileSync(path.join(root, "analyzer_ts", "src", "preamble_gen.ts"), out);
console.log("wrote analyzer_ts/src/preamble_gen.ts (" + out.length + " bytes)");
