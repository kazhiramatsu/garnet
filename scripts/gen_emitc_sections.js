#!/usr/bin/env node
// Extract the PROGRAM-INDEPENDENT sections of the Rust typed emitter's output
// (the ts_fnval_* adapter block and ts_setup_global_object) into a TS module,
// so the self-hosted typed emitter (emitc.ts) reproduces them byte-for-byte.
// Regenerate after the Rust emitter's fixed sections change:
//   node scripts/gen_emitc_sections.js <some-rust-emit.c>
// The input must be a fresh `tsaot <ir> emit` output for ANY program.
const fs = require("fs");
const path = require("path");
const src = fs.readFileSync(process.argv[2], "utf8");
const lines = src.split("\n");

function cut(startRe, endRe) {
  let s = -1;
  for (let i = 0; i < lines.length; i++) {
    if (s < 0 && startRe.test(lines[i])) s = i;
    else if (s >= 0 && endRe.test(lines[i])) return lines.slice(s, i).join("\n");
  }
  throw new Error(`section not found: ${startRe}`);
}

// adapters: first ts_fnval_ line .. the line before ts_setup_global_object
const adapters = cut(/^static tsv ts_fnval_/, /^static void ts_setup_global_object/);
// global object: its definition .. the closing brace line (next line starting `}`
// at column 0 after the open)
let g = -1, gEnd = -1;
for (let i = 0; i < lines.length; i++) {
  if (g < 0 && /^static void ts_setup_global_object/.test(lines[i])) g = i;
  else if (g >= 0 && /^\}$/.test(lines[i])) { gEnd = i; break; }
}
if (g < 0 || gEnd < 0) throw new Error("global object section not found");
const globalObj = lines.slice(g, gEnd + 1).join("\n");

const out =
  "// GENERATED by scripts/gen_emitc_sections.js from a Rust `tsaot emit` dump.\n" +
  "// Program-independent sections of the typed emitter's output. Do not edit.\n" +
  "export const EMITC_ADAPTERS: string =\n" +
  JSON.stringify(adapters + "\n") + ";\n" +
  "export const EMITC_GLOBAL_OBJECT: string =\n" +
  JSON.stringify(globalObj + "\n") + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "analyzer_ts", "src", "emitc_sections_gen.ts"), out);
console.log("wrote analyzer_ts/src/emitc_sections_gen.ts (adapters " + adapters.length + "b, globalobj " + globalObj.length + "b)");
