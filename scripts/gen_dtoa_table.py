#!/usr/bin/env python3
"""runtime/dtoa_table.h: the powers of ten of the shortest double-to-decimal conversion (Schubfach, Giulietti 2020).
For each k in [-324, 292], with 10^-k = beta 2^r and 1 <= beta < 2: g = floor(beta 2^125) + 1, split into g1 (the high 63 bits) and g0."""
K_MIN, K_MAX = -324, 292
out = ["/* generated by scripts/gen_dtoa_table.py */", f"#define DTOA_K_MIN ({K_MIN})", f"#define DTOA_K_MAX {K_MAX}",
       "static const uint64_t g_dtoa_g[2 * (DTOA_K_MAX - DTOA_K_MIN + 1)] = {"]
for k in range(K_MIN, K_MAX + 1):
    num, den = (10 ** -k, 1) if k <= 0 else (1, 10 ** k)
    # beta 2^125 = num / den 2^(125 - r): the scale that puts the quotient in [2^125, 2^126)
    shift = 125 - (num.bit_length() - den.bit_length())
    def scaled(s):
        return (num << s) // den if s >= 0 else num // (den << -s)
    q = scaled(shift)
    while q >= 1 << 126:
        shift -= 1
        q = scaled(shift)
    while q < 1 << 125:
        shift += 1
        q = scaled(shift)
    g = q + 1
    out.append(f"  0x{g >> 63:016X}u, 0x{g & ((1 << 63) - 1):016X}u,")
out.append("};")
open("runtime/dtoa_table.h", "w").write("\n".join(out) + "\n")
