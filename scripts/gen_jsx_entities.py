#!/usr/bin/env python3
"""The JSX named character references, taken from TypeScript's own table (the `entities` map its JSX
transform decodes with) and written as exporter/jsx_entities.ts: `&name;` in JSX text and string
attributes decodes to the code point(s) TypeScript gives it (docs/jsx_react_ssr_design.md).
    python3 scripts/gen_jsx_entities.py
"""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
js = (root / "exporter/node_modules/typescript/lib/typescript.js").read_text(encoding="utf8")
m = re.search(r"quot: 34,\s*amp: 38,(.*?)\n\s*\}", js, re.S)
if not m:
    sys.exit("the entity table was not found in typescript.js")
body = "quot: 34, amp: 38," + m.group(1)
pairs = re.findall(r"([A-Za-z][A-Za-z0-9]*):\s*(\d+)", body)
seen = {}
for name, cp in pairs:
    seen.setdefault(name, int(cp))
lines = ["// Generated by scripts/gen_jsx_entities.py from TypeScript's JSX entity table (do not edit).",
         f"// {len(seen)} named character references: `&name;` in JSX decodes to the code point.",
         "export const JSX_ENTITIES: Record<string, number> = {"]
for name in sorted(seen):
    lines.append(f"  {name}: {seen[name]},")
lines.append("};")
(root / "exporter/jsx_entities.ts").write_text("\n".join(lines) + "\n", encoding="utf8")
print(f"exporter/jsx_entities.ts: {len(seen)} entities")
